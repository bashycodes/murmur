/// Input / output modality set.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Hash)]
pub struct Modalities(pub u16);

impl Modalities {
    pub const TEXT: u16 = 1;
    pub const AUDIO: u16 = 2;
    pub const IMAGE: u16 = 4;
    pub const TRANSCRIPTION: u16 = 8;
    pub const FILE: u16 = 16;
    pub const VIDEO: u16 = 32;
    pub const EMBEDDINGS: u16 = 64;
    const NAMES: [(&'static str, u16); 7] = [
        ("text", Self::TEXT),
        ("audio", Self::AUDIO),
        ("image", Self::IMAGE),
        ("transcription", Self::TRANSCRIPTION),
        ("file", Self::FILE),
        ("video", Self::VIDEO),
        ("embeddings", Self::EMBEDDINGS),
    ];

    pub fn has(self, bit: u16) -> bool {
        self.0 & bit != 0
    }

    pub fn from_names<'a>(names: impl IntoIterator<Item = &'a str>) -> Self {
        let mut m = 0;
        for n in names {
            if let Some((_, b)) = Self::NAMES.iter().find(|(k, _)| *k == n) {
                m |= b;
            }
        }
        Modalities(m)
    }

    pub fn names(self) -> Vec<&'static str> {
        Self::NAMES
            .iter()
            .filter(|(_, b)| self.has(*b))
            .map(|(k, _)| *k)
            .collect()
    }
}

impl Serialize for Modalities {
    fn serialize<S: serde::Serializer>(&self, s: S) -> Result<S::Ok, S::Error> {
        self.names().serialize(s)
    }
}

impl<'de> Deserialize<'de> for Modalities {
    fn deserialize<D: serde::Deserializer<'de>>(d: D) -> Result<Self, D::Error> {
        let v: Vec<String> = Vec::deserialize(d)?;
        Ok(Self::from_names(v.iter().map(String::as_str)))
    }
}

/// USD prices (`None` = not listed). `per_audio_second` is set for path-A
/// models (their `pricing.prompt`), `per_audio_token` for chat-audio models
/// (`pricing.audio`).
#[derive(Debug, Clone, Copy, Default, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct Price {
    pub per_audio_second: Option<f64>,
    pub per_audio_token: Option<f64>,
    /// Per input token.
    pub prompt: Option<f64>,
    /// Per output token.
    pub completion: Option<f64>,
    pub request: Option<f64>,
}

impl Price {
    fn max(self, o: Price) -> Price {
        let m = |a: Option<f64>, b: Option<f64>| match (a, b) {
            (Some(a), Some(b)) => Some(a.max(b)),
            (a, b) => a.or(b),
        };
        Price {
            per_audio_second: m(self.per_audio_second, o.per_audio_second),
            per_audio_token: m(self.per_audio_token, o.per_audio_token),
            prompt: m(self.prompt, o.prompt),
            completion: m(self.completion, o.completion),
            request: m(self.request, o.request),
        }
    }
}

/// Request parameters a model accepts (`supported_parameters`).
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(default)]
pub struct ParamSet {
    pub temperature: bool,
    pub max_tokens: bool,
    pub reasoning: bool,
    pub include_reasoning: bool,
    pub stop: bool,
    pub seed: bool,
    pub response_format: bool,
}

impl ParamSet {
    fn from_list(v: Option<&Value>) -> Self {
        let has = |n: &str| {
            v.and_then(|a| a.as_array())
                .is_some_and(|a| a.iter().any(|x| x.as_str() == Some(n)))
        };
        ParamSet {
            temperature: has("temperature"),
            max_tokens: has("max_tokens") || has("max_completion_tokens"),
            reasoning: has("reasoning") || has("reasoning_effort"),
            include_reasoning: has("include_reasoning"),
            stop: has("stop"),
            seed: has("seed"),
            response_format: has("response_format"),
        }
    }
}

/// One model, trimmed from `/models` and joined with the ZDR list.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct ModelInfo {
    pub id: String,
    pub name: String,
    pub context_length: u32,
    pub input: Modalities,
    pub output: Modalities,
    /// How this model can transcribe, if at all.
    pub stt_path: Option<SttPath>,
    /// Model-level (cheapest endpoint) price.
    pub price: Price,
    /// Highest price among its ZDR endpoints (budget headroom, §2.6).
    pub zdr_price_max: Option<Price>,
    /// `false` for a per-second price that cannot be per second (§1.1).
    pub price_unit_ok: bool,
    /// At least one zero-data-retention endpoint serves it.
    pub zdr: bool,
    /// ZDR endpoint tags (`groq`, `deepinfra/us`, …).
    pub zdr_providers: Vec<String>,
    /// ZDR endpoints on Groq / Cerebras / SambaNova.
    pub fast_zdr_providers: Vec<String>,
    pub reasoning_mandatory: bool,
    /// `reasoning.supported_efforts`, as listed.
    pub reasoning_efforts: Vec<String>,
    pub supports: ParamSet,
    pub max_completion_tokens: Option<u32>,
    pub free: bool,
    pub batch_only: bool,
    pub router: bool,
    /// `/models/user` result: `Some(false)` = the account's OpenRouter
    /// privacy settings exclude it. `None` = not checked (no key).
    pub allowed_by_account: Option<bool>,
}

impl ModelInfo {
    /// Usable for speech-to-text.
    pub fn is_stt(&self) -> bool {
        self.stt_path.is_some() && !self.batch_only && !self.router
    }

    /// Usable for text cleanup: text in, text out, a chat model.
    pub fn is_cleanup(&self) -> bool {
        self.input.has(Modalities::TEXT)
            && self.output.has(Modalities::TEXT)
            && !self.output.has(Modalities::TRANSCRIPTION)
            && !self.batch_only
            && !self.router
    }

    /// The `reasoning.effort` to send: `none` when allowed, else the lowest
    /// listed effort; `None` = send no reasoning field.
    pub fn reasoning_effort(&self) -> Option<&'static str> {
        const ORDER: [&str; 7] = ["none", "minimal", "low", "medium", "high", "xhigh", "max"];
        if !self.supports.reasoning && self.reasoning_efforts.is_empty() {
            return None;
        }
        let listed = |e: &str| self.reasoning_efforts.iter().any(|x| x == e);
        if self.reasoning_efforts.is_empty() {
            return (!self.reasoning_mandatory).then_some("none");
        }
        ORDER
            .iter()
            .copied()
            .filter(|e| !(self.reasoning_mandatory && *e == "none"))
            .find(|e| listed(e))
    }

    /// Price shown in the picker, e.g. `"$0.012/h audio"`,
    /// `"≈ $0.035/h + output"`, `"≈ $0.0002 per dictation"`, `"free"`.
    pub fn price_label(&self, use_: Use) -> String {
        if self.free {
            return "free".into();
        }
        match use_ {
            Use::Stt => match self.stt_path {
                Some(SttPath::Transcriptions) => match self.price.per_audio_second {
                    Some(p) if self.price_unit_ok => format!("${}/h audio", fmt_usd(p * 3600.0)),
                    _ => "price: see usage".into(),
                },
                Some(SttPath::ChatAudio) => match self.price.per_audio_token {
                    Some(p) => format!(
                        "≈ ${}/h + output",
                        fmt_usd(p * AUDIO_TOKENS_PER_SECOND * 3600.0)
                    ),
                    None => "price: see usage".into(),
                },
                None => String::new(),
            },
            Use::Cleanup => match crate::budget::cleanup_per_dictation(self) {
                Some(c) => format!("≈ ${} per dictation", fmt_usd(c)),
                None => "price: see usage".into(),
            },
        }
    }

    /// Picker badges: `ZDR`, `fast`, `free (20/min, may log)`,
    /// `chat model, may paraphrase`, `reasoning`, `not allowed by account`.
    pub fn badges(&self, use_: Use) -> Vec<&'static str> {
        let mut b = Vec::new();
        if self.zdr {
            b.push("ZDR");
        }
        if !self.fast_zdr_providers.is_empty() {
            b.push("fast");
        }
        if self.free {
            b.push("free (20/min, may log)");
        }
        if use_ == Use::Stt && self.stt_path == Some(SttPath::ChatAudio) {
            b.push("chat model, may paraphrase");
        }
        if use_ == Use::Cleanup && self.reasoning_mandatory {
            b.push("reasoning");
        }
        if self.allowed_by_account == Some(false) {
            b.push("not allowed by your OpenRouter privacy settings");
        }
        b
    }
}

fn fmt_usd(v: f64) -> String {
    if v >= 1.0 {
        format!("{v:.2}")
    } else {
        // Two significant digits.
        let digits = (-(v.log10().floor()) as i32 + 1).clamp(2, 8) as usize;
        format!("{v:.digits$}")
    }
}

/// What the user picks a model for.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Use {
    Stt,
    Cleanup,
}

impl Use {
    pub fn parse(s: &str) -> Option<Self> {
        match s {
            "stt" => Some(Use::Stt),
            "cleanup" => Some(Use::Cleanup),
            _ => None,
        }
    }
}

/// Picker filter chips (§2.2). Default: ZDR only.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(default)]
pub struct Filters {
    pub zdr_only: bool,
    pub fast_only: bool,
    pub free_only: bool,
    /// STT only: one path.
    pub stt_path: Option<SttPath>,
}

impl Default for Filters {
    fn default() -> Self {
        Self {
            zdr_only: true,
            fast_only: false,
            free_only: false,
            stt_path: None,
        }
    }
}

#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
pub enum CatalogSource {
    Live,
    Cache,
    #[default]
    Baked,
}

#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct Catalog {
    pub fetched_at_ms: u64,
    pub source: CatalogSource,
    /// Snapshot date of a baked catalogue (`YYYY-MM-DD`).
    pub snapshot_date: Option<String>,
    /// Whether `/models/user` was consulted (a key was given).
    pub account_filtered: bool,
    pub models: Vec<ModelInfo>,
}

/// A row of a picker search (JSON for the shells).
#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct PickerRow<'a> {
    #[serde(flatten)]
    pub model: &'a ModelInfo,
    pub recommended: bool,
    pub price_label: String,
    pub badges: Vec<&'static str>,
}

impl Catalog {
    /// The baked offline fallback.
    pub fn baked() -> Catalog {
        // Raw OpenRouter JSON (trimmed), parsed like a live answer.
        let v: Value = serde_json::from_str(BAKED).expect("data/catalog-baked.json parses");
        let models = v.get("models").cloned().unwrap_or_default();
        let mut c = Catalog::from_api(&[&models], v.get("zdr"), None, 0, CatalogSource::Baked);
        c.snapshot_date = v
            .get("snapshot_date")
            .and_then(Value::as_str)
            .map(str::to_string);
        c
    }

    pub fn get(&self, id: &str) -> Option<&ModelInfo> {
        // `:nitro` / `:floor` variants are routing variants of the base.
        self.models.iter().find(|m| m.id == id).or_else(|| {
            let (base, v) = id.rsplit_once(':')?;
            matches!(v, "nitro" | "floor" | "online")
                .then(|| self.models.iter().find(|m| m.id == base))
                .flatten()
        })
    }

    pub fn stt_models(&self) -> impl Iterator<Item = &ModelInfo> {
        self.models.iter().filter(|m| m.is_stt())
    }

    pub fn cleanup_models(&self) -> impl Iterator<Item = &ModelInfo> {
        self.models.iter().filter(|m| m.is_cleanup())
    }

    pub fn is_fresh(&self, now_ms: u64) -> bool {
        self.source != CatalogSource::Baked
            && now_ms.saturating_sub(self.fetched_at_ms) < CACHE_TTL_MS
    }

    /// Picker search: id/name substring (case-insensitive, all words),
    /// filters, sorted recommended first, then by price, then id.
    pub fn search(&self, q: &str, use_: Use, f: Filters) -> Vec<&ModelInfo> {
        let words: Vec<String> = q.split_whitespace().map(|w| w.to_lowercase()).collect();
        let rec = recommended(use_);
        let mut out: Vec<&ModelInfo> = self
            .models
            .iter()
            .filter(|m| match use_ {
                Use::Stt => m.is_stt(),
                Use::Cleanup => m.is_cleanup(),
            })
            .filter(|m| !f.zdr_only || m.zdr)
            .filter(|m| !f.fast_only || !m.fast_zdr_providers.is_empty())
            .filter(|m| !f.free_only || m.free)
            .filter(|m| use_ != Use::Stt || f.stt_path.is_none() || m.stt_path == f.stt_path)
            .filter(|m| {
                let hay = format!("{} {}", m.id, m.name).to_lowercase();
                words.iter().all(|w| hay.contains(w.as_str()))
            })
            .collect();
        let rank = |m: &ModelInfo| rec.iter().position(|r| *r == m.id).unwrap_or(usize::MAX);
        out.sort_by(|a, b| {
            rank(a)
                .cmp(&rank(b))
                .then(
                    sort_price(a, use_)
                        .partial_cmp(&sort_price(b, use_))
                        .unwrap_or(std::cmp::Ordering::Equal),
                )
                .then(a.id.cmp(&b.id))
        });
        out
    }

    /// [`Catalog::search`] as picker rows.
    pub fn picker(&self, q: &str, use_: Use, f: Filters) -> Vec<PickerRow<'_>> {
        let rec = recommended(use_);
        self.search(q, use_, f)
            .into_iter()
            .map(|m| PickerRow {
                model: m,
                recommended: rec.contains(&m.id.as_str()),
                price_label: m.price_label(use_),
                badges: m.badges(use_),
            })
            .collect()
    }

    /// Build from raw OpenRouter JSON (`{data: [...]}` bodies).
    pub fn from_api(
        models: &[&Value],
        zdr: Option<&Value>,
        user_models: Option<&Value>,
        fetched_at_ms: u64,
        source: CatalogSource,
    ) -> Catalog {
        let mut zdr_by_model: HashMap<String, Vec<(String, Price)>> = HashMap::new();
        for e in data(zdr) {
            let Some(id) = e.get("model_id").and_then(Value::as_str) else {
                continue;
            };
            let tag = e
                .get("tag")
                .and_then(Value::as_str)
                .unwrap_or("")
                .to_string();
            zdr_by_model
                .entry(id.to_string())
                .or_default()
                .push((tag, parse_price(e.get("pricing"))));
        }
        let allowed: Option<HashSet<String>> = user_models.map(|u| {
            data(Some(u))
                .filter_map(|m| m.get("id").and_then(Value::as_str).map(str::to_string))
                .collect()
        });
        let mut seen = HashSet::new();
        let mut out = Vec::new();
        for m in models.iter().flat_map(|v| data(Some(v))) {
            let Some(mut info) = parse_model(m) else {
                continue;
            };
            if !seen.insert(info.id.clone()) {
                continue;
            }
            if let Some(eps) = zdr_by_model.get(&info.id) {
                info.zdr = true;
                let mut tags: Vec<String> = eps.iter().map(|(t, _)| t.clone()).collect();
                tags.sort();
                tags.dedup();
                info.fast_zdr_providers = tags
                    .iter()
                    .filter(|t| {
                        let slug = t.split('/').next().unwrap_or("");
                        FAST_PROVIDERS.iter().any(|f| slug.starts_with(f))
                    })
                    .cloned()
                    .collect();
                info.zdr_providers = tags;
                let mut max = Price::default();
                for (_, p) in eps {
                    max = max.max(normalise_endpoint_price(*p, info.stt_path));
                }
                info.zdr_price_max = Some(max);
            }
            info.allowed_by_account = allowed.as_ref().map(|a| a.contains(&info.id));
            out.push(info);
        }
        out.sort_by(|a, b| a.id.cmp(&b.id));
        Catalog {
            fetched_at_ms,
            source,
            snapshot_date: None,
            account_filtered: user_models.is_some(),
            models: out,
        }
    }

    pub fn to_json(&self) -> String {
        serde_json::to_string(self).expect("catalog serialises")
    }

    pub fn from_json(s: &str) -> Option<Catalog> {
        serde_json::from_str(s).ok()
    }
}

fn recommended(use_: Use) -> &'static [&'static str] {
    match use_ {
        Use::Stt => RECOMMENDED_STT,
        Use::Cleanup => RECOMMENDED_CLEANUP,
    }
}

fn sort_price(m: &ModelInfo, use_: Use) -> f64 {
    let p = match use_ {
        Use::Stt => m
            .price
            .per_audio_second
            .filter(|_| m.price_unit_ok)
            .or(m.price.per_audio_token.map(|t| t * AUDIO_TOKENS_PER_SECOND)),
        Use::Cleanup => crate::budget::cleanup_per_dictation(m),
    };
    p.unwrap_or(f64::MAX)
}

fn data(v: Option<&Value>) -> impl Iterator<Item = &Value> {
    v.and_then(|v| v.get("data").or(Some(v)))
        .and_then(Value::as_array)
        .into_iter()
        .flatten()
}

fn num(v: Option<&Value>) -> Option<f64> {
    let v = v?;
    let f = match v {
        Value::String(s) => s.trim().parse::<f64>().ok()?,
        Value::Number(n) => n.as_f64()?,
        _ => return None,
    };
    f.is_finite().then_some(f)
}

fn parse_price(p: Option<&Value>) -> Price {
    let g = |k: &str| num(p.and_then(|p| p.get(k)));
    Price {
        per_audio_second: None,
        per_audio_token: g("audio"),
        prompt: g("prompt"),
        completion: g("completion"),
        request: g("request").filter(|r| *r != 0.0),
    }
}

/// Path-A prices are per second in `prompt`.
fn normalise_endpoint_price(mut p: Price, path: Option<SttPath>) -> Price {
    if path == Some(SttPath::Transcriptions) {
        p.per_audio_second = p.prompt;
        p.prompt = None;
        p.completion = None;
    }
    p
}

fn names(v: Option<&Value>) -> Modalities {
    Modalities::from_names(
        v.and_then(Value::as_array)
            .into_iter()
            .flatten()
            .filter_map(Value::as_str),
    )
}

/// One `/models` entry (lenient: unknown fields ignored, missing default).
pub fn parse_model(m: &Value) -> Option<ModelInfo> {
    let id = m.get("id")?.as_str()?.trim().to_string();
    if id.is_empty() {
        return None;
    }
    let arch = m.get("architecture");
    let mut input = names(arch.and_then(|a| a.get("input_modalities")));
    let output = names(arch.and_then(|a| a.get("output_modalities")));
    if input.0 == 0 {
        // Old-style `modality: "text+audio->text"`.
        if let Some(md) = arch.and_then(|a| a.get("modality")).and_then(Value::as_str) {
            input = Modalities::from_names(md.split("->").next().unwrap_or("").split('+'));
        }
    }
    let stt_path = if output.has(Modalities::TRANSCRIPTION) {
        Some(SttPath::Transcriptions)
    } else if input.has(Modalities::AUDIO) && output.has(Modalities::TEXT) {
        Some(SttPath::ChatAudio)
    } else {
        None
    };
    let price = normalise_endpoint_price(parse_price(m.get("pricing")), stt_path);
    let router = id.starts_with("openrouter/")
        || [price.prompt, price.completion, price.per_audio_second]
            .iter()
            .any(|p| p.is_some_and(|p| p < 0.0));
    let free = !router
        && (id.ends_with(":free")
            || ([price.prompt, price.completion, price.per_audio_second]
                .iter()
                .all(|p| p.is_none_or(|p| p == 0.0))
                && [price.prompt, price.per_audio_second]
                    .iter()
                    .any(Option::is_some)));
    let price_unit_ok = match stt_path {
        Some(SttPath::Transcriptions) => price
            .per_audio_second
            .is_none_or(|p| (0.0..=MAX_SANE_PER_SECOND).contains(&p)),
        _ => !router,
    };
    let reasoning = m.get("reasoning");
    let reasoning_efforts = reasoning
        .and_then(|r| r.get("supported_efforts"))
        .and_then(Value::as_array)
        .into_iter()
        .flatten()
        .filter_map(Value::as_str)
        .map(str::to_string)
        .collect();
    let u32_of = |v: Option<&Value>| {
        v.and_then(Value::as_u64)
            .map(|n| n.min(u32::MAX as u64) as u32)
    };
    Some(ModelInfo {
        name: m
            .get("name")
            .and_then(Value::as_str)
            .unwrap_or(&id)
            .to_string(),
        context_length: u32_of(m.get("context_length")).unwrap_or(0),
        input,
        output,
        stt_path,
        price,
        zdr_price_max: None,
        price_unit_ok,
        zdr: false,
        zdr_providers: Vec::new(),
        fast_zdr_providers: Vec::new(),
        reasoning_mandatory: reasoning
            .and_then(|r| r.get("mandatory"))
            .and_then(Value::as_bool)
            .unwrap_or(false),
        reasoning_efforts,
        supports: ParamSet::from_list(m.get("supported_parameters")),
        max_completion_tokens: u32_of(m.pointer("/top_provider/max_completion_tokens")),
        free,
        batch_only: id.ends_with(":batch"),
        router,
        allowed_by_account: None,
        id,
    })
}

fn now_ms() -> u64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map_or(0, |d| d.as_millis() as u64)
}

/// GET a JSON list, following same-origin `links.next` (≤ 10 pages).
fn get_paged(
    api: &Api,
    path: &str,
    key: Option<&SecretString>,
    deadline: Instant,
) -> Result<Value, CloudError> {
    let mut url = api.url(path);
    let mut all = Vec::new();
    for _ in 0..10 {
        let mut rb = api.client().get(&url);
        if let Some(k) = key {
            rb = rb.bearer_auth(k.expose());
        }
        let v = http::json(http::send(rb, deadline)?)?;
        if let Some(a) = v.get("data").and_then(Value::as_array) {
            all.extend(a.iter().cloned());
        } else if let Some(a) = v.as_array() {
            all.extend(a.iter().cloned());
        }
        match v
            .pointer("/links/next")
            .and_then(Value::as_str)
            .filter(|s| !s.is_empty())
            .and_then(|n| api.resolve_same_origin(n))
        {
            Some(n) if n != url => url = n,
            _ => break,
        }
    }
    Ok(serde_json::json!({ "data": all }))
}

/// Fetch a live catalogue: models (all + transcription), the ZDR list and,
/// with a key, the account-filtered list, in parallel under one deadline.
/// The models list is required; the others degrade (ZDR unknown = `false`).
pub fn refresh(api: &Api, key: Option<&SecretString>) -> Result<Catalog, CloudError> {
    let deadline = Instant::now() + REFRESH_TIMEOUT;
    let (all, tr, zdr, user) = std::thread::scope(|s| {
        let all = s.spawn(|| {
            get_paged(
                api,
                "/models?output_modalities=all&limit=1000",
                None,
                deadline,
            )
        });
        let tr = s.spawn(|| {
            get_paged(
                api,
                "/models?output_modalities=transcription&limit=1000",
                None,
                deadline,
            )
        });
        let zdr = s.spawn(|| get_paged(api, "/endpoints/zdr", None, deadline));
        let user = key.map(|k| {
            s.spawn(move || {
                get_paged(
                    api,
                    "/models/user?output_modalities=all&limit=1000",
                    Some(k),
                    deadline,
                )
            })
        });
        (
            all.join().unwrap_or(Err(CloudError::Malformed)),
            tr.join().unwrap_or(Err(CloudError::Malformed)),
            zdr.join().unwrap_or(Err(CloudError::Malformed)),
            user.map(|u| u.join().unwrap_or(Err(CloudError::Malformed))),
        )
    });
    let all = all?;
    let tr = tr.ok();
    let zdr = zdr.ok();
    let user = user.and_then(Result::ok);
    let mut models = vec![&all];
    if let Some(t) = &tr {
        models.push(t);
    }
    Ok(Catalog::from_api(
        &models,
        zdr.as_ref(),
        user.as_ref(),
        now_ms(),
        CatalogSource::Live,
    ))
}

/// Look up one model id that is not in the catalogue (free-text id, §2.2):
/// `GET /models/{author}/{slug}/endpoints` gives its architecture.
pub fn lookup_model(api: &Api, id: &str) -> Result<ModelInfo, CloudError> {
    if !valid_model_id(id) || id.split(':').next().unwrap_or("").split('/').count() != 2 {
        return Err(CloudError::BadRequest {
            status: 400,
            code: Some("model_id".into()),
        });
    }
    let base = id.split(':').next().unwrap_or(id);
    let deadline = Instant::now() + Duration::from_secs(5);
    let v = http::json(http::send(
        api.client()
            .get(api.url(&format!("/models/{base}/endpoints"))),
        deadline,
    )?)?;
    let d = v.get("data").ok_or(CloudError::Malformed)?;
    let mut m = d.clone();
    if m.get("id").is_none() {
        m["id"] = Value::String(base.into());
    }
    // Endpoints carry pricing; take the cheapest as the model price.
    if m.get("pricing").is_none() {
        if let Some(p) = d
            .get("endpoints")
            .and_then(Value::as_array)
            .and_then(|e| e.first())
            .and_then(|e| e.get("pricing"))
        {
            m["pricing"] = p.clone();
        }
    }
    // Parameters live per endpoint; the model supports what any endpoint
    // does (the /models list carries the same union).
    if m.get("supported_parameters").is_none() {
        let mut params: Vec<Value> = Vec::new();
        for p in d
            .get("endpoints")
            .and_then(Value::as_array)
            .into_iter()
            .flatten()
            .filter_map(|e| e.get("supported_parameters").and_then(Value::as_array))
            .flatten()
        {
            if !params.contains(p) {
                params.push(p.clone());
            }
        }
        m["supported_parameters"] = Value::Array(params);
    }
    let mut info = parse_model(&m).ok_or(CloudError::Malformed)?;
    info.id = id.to_string();
    Ok(info)
}

/// The shells' catalogue handle: memory → cache file → baked, plus refresh.
pub struct CatalogStore {
    cache_file: Option<PathBuf>,
    api: Api,
    current: Mutex<Option<Catalog>>,
}

impl CatalogStore {
    /// `cache_file`: e.g. `<cacheDir>/openrouter-catalog.json`.
    pub fn new(cache_file: impl Into<PathBuf>) -> Self {
        Self::with_api(Some(cache_file.into()), Api::new())
    }

    /// No cache file (tests, CLI).
    pub fn in_memory() -> Self {
        Self::with_api(None, Api::new())
    }

    pub fn with_api(cache_file: Option<PathBuf>, api: Api) -> Self {
        Self {
            cache_file,
            api,
            current: Mutex::new(None),
        }
    }

    /// Best catalogue available without network.
    pub fn current(&self) -> Catalog {
        let mut cur = self.current.lock().unwrap_or_else(|e| e.into_inner());
        if let Some(c) = cur.as_ref() {
            return c.clone();
        }
        let c = self.load_cache().unwrap_or_else(Catalog::baked);
        *cur = Some(c.clone());
        c
    }

    fn load_cache(&self) -> Option<Catalog> {
        let p = self.cache_file.as_ref()?;
        let s = std::fs::read_to_string(p).ok()?;
        let mut c = Catalog::from_json(&s)?;
        if c.models.is_empty() {
            return None;
        }
        c.source = CatalogSource::Cache;
        Some(c)
    }

    /// Whether the current catalogue is older than the TTL (or baked).
    pub fn is_stale(&self) -> bool {
        !self.current().is_fresh(now_ms())
    }

    /// Refresh from OpenRouter unless the cache is fresh (or `force`), and
    /// write the cache file. Blocking (≤ 10 s); call off the UI thread. On
    /// error the previous catalogue stays current.
    pub fn refresh(&self, key: Option<&SecretString>, force: bool) -> Result<Catalog, CloudError> {
        if !force && !self.is_stale() {
            return Ok(self.current());
        }
        let c = refresh(&self.api, key)?;
        if let Some(p) = &self.cache_file {
            let tmp = p.with_extension("json.tmp");
            if std::fs::write(&tmp, c.to_json()).is_ok() {
                let _ = std::fs::rename(&tmp, p);
            }
        }
        *self.current.lock().unwrap_or_else(|e| e.into_inner()) = Some(c.clone());
        Ok(c)
    }

    /// The model, from the current catalogue.
    pub fn model(&self, id: &str) -> Option<ModelInfo> {
        self.current().get(id).cloned()
    }

    /// Picker rows as a JSON array. `use_` = `"stt" | "cleanup"`;
    /// `filters_json` = [`Filters`] (missing fields default; invalid = default).
    pub fn search_json(&self, use_: &str, query: &str, filters_json: &str) -> String {
        let Some(u) = Use::parse(use_) else {
            return "[]".into();
        };
        let f: Filters = serde_json::from_str(filters_json).unwrap_or_default();
        let c = self.current();
        serde_json::to_string(&c.picker(query, u, f)).unwrap_or_else(|_| "[]".into())
    }

    /// `{source, fetched_at_ms, snapshot_date, models, stt, cleanup}` for
    /// the "Refresh models" status line and the D21 event.
    pub fn status_json(&self) -> String {
        let c = self.current();
        serde_json::json!({
            "source": c.source,
            "fetched_at_ms": c.fetched_at_ms,
            "snapshot_date": c.snapshot_date,
            "models": c.models.len(),
            "stt": c.stt_models().count(),
            "cleanup": c.cleanup_models().count(),
        })
        .to_string()
    }
}

static DEFAULT_STORE: OnceLock<Mutex<Option<Arc<CatalogStore>>>> = OnceLock::new();

/// Register the shell's store so the STT adapter and cleaner can resolve a
/// model's path and prices without each holding one.
pub fn set_default_store(s: Option<Arc<CatalogStore>>) {
    *DEFAULT_STORE
        .get_or_init(|| Mutex::new(None))
        .lock()
        .unwrap_or_else(|e| e.into_inner()) = s;
}

pub fn default_store() -> Option<Arc<CatalogStore>> {
    DEFAULT_STORE
        .get()?
        .lock()
        .unwrap_or_else(|e| e.into_inner())
        .clone()
}

/// The model from the registered store, else the baked catalogue.
pub fn resolve(id: &str) -> Option<ModelInfo> {
    if let Some(m) = default_store().and_then(|s| s.model(id)) {
        return Some(m);
    }
    static BAKED_CAT: OnceLock<Catalog> = OnceLock::new();
    BAKED_CAT.get_or_init(Catalog::baked).get(id).cloned()
}

