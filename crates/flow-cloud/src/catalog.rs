//! OpenRouter model catalogue (D28 §2.2): every model that can transcribe
//! (path A `/audio/transcriptions`, path B chat `input_audio`) or clean up
//! text, with prices, modalities, context length and whether a
//! zero-data-retention endpoint serves it.
//!
//! Sources, all on [`crate::api::HOST`]:
//! * `GET /models?output_modalities=all` (+ `=transcription`, in case the
//!   server's "all" ever omits them), following same-origin `links.next`;
//! * `GET /endpoints/zdr` (no key needed);
//! * with a key, `GET /models/user?output_modalities=all`: models the
//!   account's own privacy settings allow.
//!
//! Lookup order for the shells ([`CatalogStore::current`]): memory, the
//! 24 h cache file (path chosen by the caller), the baked snapshot
//! (`data/catalog-baked.json`, generated by `tools/gen-openrouter-catalog.py`
//! from the dated snapshots in `docs/proposals/data/`). Nothing here sends
//! user data; a fetch reveals only the IP to openrouter.ai.

